#!/usr/bin/env python3
"""KindWindow Step 15 — regenerate report figures from committed tables.

Reads ONLY already-committed, saved metrics (no real data, no test
re-scoring, no refitting) and writes SVG figures under reports/figures/.

Figures produced:
  runtime_vs_events.svg  (F6) — median end-to-end runtime vs input events
  memory_vs_events.svg   (F7) — median peak tree memory vs input events
  risk_coverage.svg      (F5) — selective (abstention) Brier vs coverage

Also verifies the committed per-home Brier figure:
  reports/figures/per_home_brier.svg (F3) is checked, never rewritten —
  it was generated by hand in SVG in Step 11 and its values are validated
  against reports/tables/test_scores.csv with --check.

Usage:
  uv run --locked python scripts/make_figures.py [--check]
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "reports" / "tables"
BENCH = ROOT / "reports" / "benchmarks"
FIGURES = ROOT / "reports" / "figures"


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def svg_scatter_bars(
    title: str,
    xlabel: str,
    ylabel: str,
    x_values: list[float],
    series: dict[str, list[float | None]],
    x_labels: list[str],
    y_format: str = "{:.0f}",
    note: str = "",
) -> str:
    """Minimal grouped-bar SVG. x is categorical (workload); one bar per series."""
    width, height = 640, 420
    left, right, top, bottom = 70, 20, 44, 64
    plot_w = width - left - right
    plot_h = height - top - bottom
    all_y = [v for vals in series.values() for v in vals if v is not None]
    ymax = max(all_y) * 1.12 if all_y else 1.0
    colors = {"pandas": "#1f77b4", "spark": "#d62728"}
    n_groups = len(x_labels)
    group_w = plot_w / n_groups
    bar_w = min(64, (group_w * 0.7) / max(1, len(series)))
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        'viewBox="0 0 640 420" role="img">',
        '<rect width="640" height="420" fill="white"/>',
        f'<text x="320" y="24" text-anchor="middle" font-size="15" '
        f'font-family="sans-serif">{title}</text>',
    ]
    # y gridlines + labels (4 ticks)
    for i in range(5):
        val = ymax * i / 4
        y = top + plot_h - (plot_h * i / 4)
        parts.append(
            f'<line x1="{left}" y1="{y:.1f}" x2="{width - right}" y2="{y:.1f}" stroke="#dddddd"/>'
        )
        parts.append(
            f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end" font-size="11" '
            f'font-family="sans-serif">{y_format.format(val)}</text>'
        )
    for gi, label in enumerate(x_labels):
        cx = left + group_w * (gi + 0.5)
        parts.append(
            f'<text x="{cx:.1f}" y="{height - 34}" text-anchor="middle" font-size="12" '
            f'font-family="sans-serif">{label}</text>'
        )
        for si, (name, vals) in enumerate(series.items()):
            v = vals[gi]
            offset = (si - (len(series) - 1) / 2) * bar_w
            if v is None:
                parts.append(
                    f'<text x="{cx + offset:.1f}" y="{top + plot_h - 6}" '
                    'text-anchor="middle" font-size="11" font-family="sans-serif" '
                    'fill="#d62728">failed</text>'
                )
                continue
            bar_h = plot_h * v / ymax
            x0 = cx + offset - bar_w / 2
            y0 = top + plot_h - bar_h
            parts.append(
                f'<rect x="{x0:.1f}" y="{y0:.1f}" width="{bar_w}" '
                f'height="{bar_h:.1f}" fill="{colors.get(name, "#888888")}"/>'
            )
            parts.append(
                f'<text x="{cx + offset:.1f}" y="{y0 - 4:.1f}" text-anchor="middle" '
                f'font-size="11" font-family="sans-serif">'
                f"{y_format.format(v)}</text>"
            )
    legend_x = width - right - 150
    for si, name in enumerate(series):
        ly = top + 8 + si * 18
        parts.append(
            f'<rect x="{legend_x}" y="{ly}" width="12" height="12" '
            f'fill="{colors.get(name, "#888888")}"/>'
        )
        parts.append(
            f'<text x="{legend_x + 17}" y="{ly + 10}" font-size="12" '
            f'font-family="sans-serif">{name}</text>'
        )
    parts.append(
        f'<text x="{left}" y="{height - 12}" font-size="11" '
        f'font-family="sans-serif" fill="#555555">{xlabel}</text>'
    )
    parts.append(
        f'<text x="16" y="{top + plot_h / 2}" font-size="11" '
        f'font-family="sans-serif" fill="#555555" '
        f'transform="rotate(-90 16 {top + plot_h / 2})">{ylabel}</text>'
    )
    if note:
        parts.append(
            f'<text x="{left}" y="{height - 26}" font-size="10" '
            f'font-family="sans-serif" fill="#555555">{note}</text>'
        )
    parts.append("</svg>")
    return "\n".join(parts)


def figure_runtime() -> Path:
    rows = read_csv(BENCH / "summary.csv")
    order = ["synthetic-1m", "real", "synthetic-10m"]
    labels = ["1M synthetic", "Real (78.3M)", "10M synthetic"]
    series: dict[str, list[float | None]] = {"pandas": [], "spark": []}
    for workload in order:
        for engine in ("pandas", "spark"):
            match = [r for r in rows if r["workload"] == workload and r["engine"] == engine]
            val = match[0]["median_elapsed_seconds"] if match else ""
            series[engine].append(float(val) if val else None)
    svg = svg_scatter_bars(
        "RQ2 — median end-to-end runtime (n=3, parity-passing pairs only)",
        "Workload (input events)",
        "Median runtime (s)",
        [],
        series,
        labels,
        y_format="{:.0f}",
        note="10M pandas: 0/3, memory_limit — no bar, no ordering claimed at 10M.",
    )
    out = FIGURES / "runtime_vs_events.svg"
    out.write_text(svg, encoding="utf-8")
    return out


def figure_memory() -> Path:
    rows = read_csv(BENCH / "summary.csv")
    order = ["synthetic-1m", "real", "synthetic-10m"]
    labels = ["1M synthetic", "Real (78.3M)", "10M synthetic"]
    series: dict[str, list[float | None]] = {"pandas": [], "spark": []}
    for workload in order:
        for engine in ("pandas", "spark"):
            match = [r for r in rows if r["workload"] == workload and r["engine"] == engine]
            val = match[0]["median_peak_tree_bytes"] if match else ""
            gb = float(val) / 1e9 if val else None
            series[engine].append(gb)
    svg = svg_scatter_bars(
        "RQ2 — median peak process-tree memory (n=3; cap 5.82 GB)",
        "Workload (input events)",
        "Median peak tree RSS (GB)",
        [],
        series,
        labels,
        y_format="{:.2f}",
        note="10M pandas hit the 5.82 GB cap in all 3 attempts (peak shown is the cap).",
    )
    out = FIGURES / "memory_vs_events.svg"
    out.write_text(svg, encoding="utf-8")
    return out


def figure_risk_coverage() -> Path:
    rows = read_csv(TABLES / "test_scores.csv")
    points = []
    for r in rows:
        if r["model"] in (
            "forest-d10-leaf10-calibrated-retained-0.5",
            "forest-d10-leaf10-calibrated-retained-1.0",
        ):
            coverage = int(r["n"]) / 206953
            points.append((coverage, float(r["brier"]), r["model"]))
    points.sort()
    width, height = 640, 420
    left, right, top, bottom = 70, 20, 44, 64
    plot_w, plot_h = width - left - right, height - top - bottom
    xmax, ymax = 1.0, 0.16
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="420" '
        'viewBox="0 0 640 420" role="img">',
        '<rect width="640" height="420" fill="white"/>',
        '<text x="320" y="24" text-anchor="middle" font-size="15" '
        'font-family="sans-serif">RQ3 — selective Brier vs coverage '
        "(frozen gates, test)</text>",
    ]
    for i in range(5):
        val = ymax * i / 4
        y = top + plot_h - (plot_h * i / 4)
        parts.append(
            f'<line x1="{left}" y1="{y:.1f}" x2="{width - right}" y2="{y:.1f}" stroke="#dddddd"/>'
        )
        parts.append(
            f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end" font-size="11" '
            f'font-family="sans-serif">{val:.2f}</text>'
        )
    for i in range(6):
        val = i / 5
        x = left + plot_w * val
        parts.append(
            f'<text x="{x:.1f}" y="{height - 34}" text-anchor="middle" font-size="11" '
            f'font-family="sans-serif">{val:.1f}</text>'
        )
    coords = []
    for coverage, brier, _model in points:
        x = left + plot_w * coverage / xmax
        y = top + plot_h - plot_h * brier / ymax
        coords.append((x, y, coverage, brier))
    if len(coords) == 2:
        (x1, y1, _, _), (x2, y2, _, _) = coords
        parts.append(
            f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            'stroke="#1f77b4" stroke-width="2"/>'
        )
    for x, y, coverage, brier in coords:
        parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="6" fill="#1f77b4"/>')
        parts.append(
            f'<text x="{x + 10:.1f}" y="{y - 8:.1f}" font-size="12" '
            f'font-family="sans-serif">coverage {coverage:.4f}, Brier {brier:.4f}</text>'
        )
    parts.append(
        f'<text x="{left}" y="{height - 12}" font-size="11" font-family="sans-serif" '
        'fill="#555555">Coverage (retained / eligible test windows)</text>'
    )
    parts.append(
        f'<text x="16" y="{top + plot_h / 2}" font-size="11" font-family="sans-serif" '
        'fill="#555555" transform="rotate(-90 16 '
        f'{top + plot_h / 2})">Macro Brier on retained (lower is better)</text>'
    )
    parts.append(
        f'<text x="{left}" y="{height - 26}" font-size="10" font-family="sans-serif" '
        'fill="#555555">Only the measured retentions are plotted (50% and 100%); '
        "75% was omitted in the reduced Step 11 scope — no interpolation.</text>"
    )
    parts.append("</svg>")
    out = FIGURES / "risk_coverage.svg"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out


def check_per_home_brier() -> bool:
    """Validate the committed hand-drawn F3 figure against test_scores.csv.

    The figure encodes values as bar heights (no numeric labels): the
    y-axis runs 0.00 at y=350.0 to 0.25 at y=42.3, so one Brier unit is
    (350.0 - 42.3) / 0.25 = 1230.8 px. Bars appear in per-home order
    (test_scores.csv order), blue #2563eb = frozen calibrated,
    amber #f59e0b = recency baseline.
    """
    import re

    rows = read_csv(TABLES / "test_scores.csv")
    svg = (FIGURES / "per_home_brier.svg").read_text(encoding="utf-8")
    rects = re.findall(
        r'<rect x="[\d.]+" y="[\d.]+" width="16\.3" height="([\d.]+)" fill="(#[0-9a-f]+)"/>',
        svg,
    )
    homes = []
    frozen: dict[str, float] = {}
    recency: dict[str, float] = {}
    for r in rows:
        if r["model"] == "forest-d10-leaf10-calibrated":
            homes.append(r["home"])
            frozen[r["home"]] = float(r["brier"])
        elif r["model"] == "recency-baseline":
            recency[r["home"]] = float(r["brier"])
    ok = True
    if len(rects) != 2 * len(homes):
        print(f"MISMATCH: expected {2 * len(homes)} bars, found {len(rects)}")
        return False
    px_per_unit = (350.0 - 42.3) / 0.25
    for i, home in enumerate(homes):
        for fill, expected in (("#2563eb", frozen[home]), ("#f59e0b", recency[home])):
            height, color = (
                float(rects[2 * i + (0 if fill == "#2563eb" else 1)][0]),
                rects[2 * i + (0 if fill == "#2563eb" else 1)][1],
            )
            if color != fill:
                print(f"MISMATCH: {home} bar color {color} != {fill}")
                ok = False
            implied = height / px_per_unit
            if abs(implied - expected) > 0.001:
                print(f"MISMATCH: {home} {fill} bar implies {implied:.4f}, CSV {expected:.4f}")
                ok = False
    print("per_home_brier.svg check:", "PASS" if ok else "FAIL")
    return ok


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="only verify per_home_brier.svg")
    args = parser.parse_args(argv)
    if args.check:
        return 0 if check_per_home_brier() else 1
    for path in (figure_runtime(), figure_memory(), figure_risk_coverage()):
        print(f"wrote {path.relative_to(ROOT)}")
    if not check_per_home_brier():
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
